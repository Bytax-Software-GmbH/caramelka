/** Russische Mehrzahl: 1 торт · 2–4 торта · 5+ тортов (mit 11–14-Ausnahme). */
function pluralRu(one: string, few: string, many: string) {
  return (n: number) => {
    const m10 = n % 10;
    const m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return `${n} ${one}`;
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return `${n} ${few}`;
    return `${n} ${many}`;
  };
}

